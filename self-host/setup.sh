#!/usr/bin/env bash
# =============================================================================
# SoundDocs self-host bootstrap.
#
# Generates self-host/.env with strong secrets:
#   - POSTGRES_PASSWORD       (random)
#   - DASHBOARD_PASSWORD      (random)
#   - SECRET_KEY_BASE         (random)
#   - JWT_SECRET              (random, >= 40 hex chars)
#   - ANON_KEY                (HS256 JWT {role:anon},        signed by JWT_SECRET)
#   - SERVICE_ROLE_KEY        (HS256 JWT {role:service_role},signed by JWT_SECRET)
#   - VITE_SUPABASE_URL       (= the local Kong public URL)
#   - VITE_SUPABASE_ANON_KEY  (= ANON_KEY)
#
# JWT signing is implemented in pure bash + openssl. If openssl is missing the
# script still writes random secrets but leaves ANON_KEY / SERVICE_ROLE_KEY
# blank and tells you how to generate them.
#
# Usage:
#   ./setup.sh            # creates .env (refuses to overwrite an existing one)
#   ./setup.sh --force    # overwrite an existing .env
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.env"
EXAMPLE_FILE="${SCRIPT_DIR}/.env.example"

FORCE=0
if [ "${1:-}" = "--force" ]; then
  FORCE=1
fi

if [ -f "$ENV_FILE" ] && [ "$FORCE" -ne 1 ]; then
  echo "ERROR: ${ENV_FILE} already exists. Use --force to overwrite." >&2
  exit 1
fi

# --- Config you can tweak (must stay consistent with each other) -------------
KONG_HTTP_PORT="${KONG_HTTP_PORT:-8000}"
WEB_PORT="${WEB_PORT:-3000}"
PUBLIC_URL="http://localhost:${KONG_HTTP_PORT}"
SITE_URL="http://localhost:${WEB_PORT}"
JWT_EXPIRY_YEARS=5

# --- base64url helper --------------------------------------------------------
b64url() {
  # stdin -> base64url (no padding)
  openssl base64 -A | tr '+/' '-_' | tr -d '='
}

# --- random secret helpers ---------------------------------------------------
rand_hex() {
  # $1 = number of bytes
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    # Fallback: /dev/urandom
    head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

# --- HS256 JWT signer (pure bash + openssl) ----------------------------------
# make_jwt <role> <secret>  -> prints a signed JWT
make_jwt() {
  local role="$1" secret="$2"
  local iat exp header payload signing_input sig
  iat="$(date +%s)"
  exp=$(( iat + JWT_EXPIRY_YEARS * 365 * 24 * 3600 ))

  header='{"alg":"HS256","typ":"JWT"}'
  payload="{\"role\":\"${role}\",\"iss\":\"supabase\",\"iat\":${iat},\"exp\":${exp}}"

  local h p
  h="$(printf '%s' "$header"  | b64url)"
  p="$(printf '%s' "$payload" | b64url)"
  signing_input="${h}.${p}"

  # HMAC-SHA256 with the raw secret, output base64url.
  sig="$(printf '%s' "$signing_input" \
    | openssl dgst -sha256 -hmac "$secret" -binary \
    | b64url)"

  printf '%s.%s' "$signing_input" "$sig"
}

echo "[setup] Generating secrets ..."
POSTGRES_PASSWORD="$(rand_hex 24)"
DASHBOARD_PASSWORD="$(rand_hex 12)"
SECRET_KEY_BASE="$(rand_hex 32)"
JWT_SECRET="$(rand_hex 24)"  # 24 bytes -> 48 hex chars (>= 40 required)

ANON_KEY=""
SERVICE_ROLE_KEY=""
HAVE_OPENSSL=0
if command -v openssl >/dev/null 2>&1; then
  HAVE_OPENSSL=1
  echo "[setup] Deriving ANON_KEY and SERVICE_ROLE_KEY (HS256, signed by JWT_SECRET) ..."
  ANON_KEY="$(make_jwt anon "$JWT_SECRET")"
  SERVICE_ROLE_KEY="$(make_jwt service_role "$JWT_SECRET")"
else
  echo "[setup] WARNING: openssl not found. Random secrets were generated, but" >&2
  echo "[setup]          ANON_KEY / SERVICE_ROLE_KEY were left BLANK." >&2
  echo "[setup]          Generate them from your JWT_SECRET here:" >&2
  echo "[setup]          https://supabase.com/docs/guides/self-hosting#api-keys" >&2
  echo "[setup]          (use role 'anon' and role 'service_role'), then paste" >&2
  echo "[setup]          them into ${ENV_FILE} AND set VITE_SUPABASE_ANON_KEY=ANON_KEY." >&2
fi

# --- Write .env --------------------------------------------------------------
echo "[setup] Writing ${ENV_FILE} ..."
cat > "$ENV_FILE" <<EOF
# Generated by setup.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Do NOT commit this file.

############################################################
# SECRETS
############################################################
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
JWT_SECRET=${JWT_SECRET}
ANON_KEY=${ANON_KEY}
SERVICE_ROLE_KEY=${SERVICE_ROLE_KEY}
SECRET_KEY_BASE=${SECRET_KEY_BASE}
DASHBOARD_USERNAME=supabase
DASHBOARD_PASSWORD=${DASHBOARD_PASSWORD}

############################################################
# WEB APP (baked into the bundle at build time)
############################################################
VITE_SUPABASE_URL=${PUBLIC_URL}
VITE_SUPABASE_ANON_KEY=${ANON_KEY}
WEB_PORT=${WEB_PORT}

############################################################
# PUBLIC URLS
############################################################
SUPABASE_PUBLIC_URL=${PUBLIC_URL}
API_EXTERNAL_URL=${PUBLIC_URL}
SITE_URL=${SITE_URL}
ADDITIONAL_REDIRECT_URLS=

############################################################
# DATABASE
############################################################
POSTGRES_HOST=db
POSTGRES_DB=postgres
POSTGRES_PORT=5432

############################################################
# KONG PORTS
############################################################
KONG_HTTP_PORT=${KONG_HTTP_PORT}
KONG_HTTPS_PORT=8443

############################################################
# AUTH
############################################################
JWT_EXPIRY=3600
DISABLE_SIGNUP=false
ENABLE_EMAIL_SIGNUP=true
ENABLE_EMAIL_AUTOCONFIRM=true
ENABLE_ANONYMOUS_USERS=false
ENABLE_PHONE_SIGNUP=false
ENABLE_PHONE_AUTOCONFIRM=false
SMTP_ADMIN_EMAIL=admin@example.com
SMTP_HOST=supabase-mail
SMTP_PORT=2500
SMTP_USER=fake_mail_user
SMTP_PASS=fake_mail_password
SMTP_SENDER_NAME=fake_sender
MAILER_URLPATHS_INVITE=/auth/v1/verify
MAILER_URLPATHS_CONFIRMATION=/auth/v1/verify
MAILER_URLPATHS_RECOVERY=/auth/v1/verify
MAILER_URLPATHS_EMAIL_CHANGE=/auth/v1/verify

############################################################
# EDGE FUNCTIONS
############################################################
FUNCTIONS_VERIFY_JWT=false

############################################################
# POSTGREST
############################################################
PGRST_DB_SCHEMAS=public,storage,graphql_public

############################################################
# STORAGE
############################################################
STORAGE_TENANT_ID=stub
REGION=stub
GLOBAL_S3_BUCKET=stub

############################################################
# STUDIO
############################################################
STUDIO_DEFAULT_ORGANIZATION=SoundDocs
STUDIO_DEFAULT_PROJECT=SoundDocs

############################################################
# IMGPROXY
############################################################
IMGPROXY_AUTO_WEBP=true
EOF

chmod 600 "$ENV_FILE" 2>/dev/null || true

echo ""
echo "[setup] Done. Wrote ${ENV_FILE}"
echo "[setup]   Studio user:     supabase"
echo "[setup]   Studio password: ${DASHBOARD_PASSWORD}"
if [ "$HAVE_OPENSSL" -eq 1 ]; then
  echo "[setup]   ANON_KEY / SERVICE_ROLE_KEY were derived from JWT_SECRET."
else
  echo "[setup]   ACTION REQUIRED: fill in ANON_KEY, SERVICE_ROLE_KEY and"
  echo "[setup]   VITE_SUPABASE_ANON_KEY in ${ENV_FILE} (openssl was missing)."
fi
echo ""
echo "Next steps:"
echo "  cd \"${SCRIPT_DIR}\""
echo "  docker compose up -d            # start the stack (first run builds web + applies migrations)"
echo "  docker compose logs -f supabase-migrate   # watch migrations apply"
echo ""
echo "Then open:"
echo "  SoundDocs app:    ${SITE_URL}"
echo "  Supabase Studio:  ${PUBLIC_URL}   (login: supabase / the password above)"
